    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nombre = jTextField1.getText().trim();
        String contrasenia = new String(jPasswordField1.getPassword());
        String contrasenia2 = new String(jPasswordField2.getPassword());
        String casa = (String) jComboBox1.getSelectedItem();

        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El usuario no puede estar vacío", "ERROR", JOptionPane.ERROR_MESSAGE);
        } else if (contrasenia.length() < 6) {
            JOptionPane.showMessageDialog(this, "La contraseña debe de ser más de 6 caracteres", "ERROR", JOptionPane.ERROR_MESSAGE);
        } else if (!contrasenia.equals(contrasenia2)) {
            JOptionPane.showMessageDialog(this, "La contraseñas no coinciden", "ERROR", JOptionPane.ERROR_MESSAGE);
        } else if (!jCheckBox1.isSelected()) {
            JOptionPane.showMessageDialog(this, "La casilla debe estar marcada", "ERROR", JOptionPane.ERROR_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "Bienvenido a " + casa + ", " + nombre);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

