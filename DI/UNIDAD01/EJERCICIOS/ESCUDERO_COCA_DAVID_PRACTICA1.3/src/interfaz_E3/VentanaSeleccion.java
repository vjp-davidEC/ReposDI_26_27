    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nombre = jTextField1.getText().trim();
        String clase = (String) jComboBox1.getSelectedItem();
        
        if (nombre.isEmpty()) {
            jLabel3.setText("Error: Escribe un nombre para continuar");
        } else {
            jLabel3.setText("");
            
            Personaje miPersonaje;
            if (clase.equals("Guerrero")) {
                miPersonaje = new Guerrero(nombre);
            } else if (clase.equals("Mago")) {
                miPersonaje = new Mago(nombre);
            } else {
                miPersonaje = new Arquero(nombre);
            }
            
            new VentanaCombate(miPersonaje).setVisible(true);
            this.dispose();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

