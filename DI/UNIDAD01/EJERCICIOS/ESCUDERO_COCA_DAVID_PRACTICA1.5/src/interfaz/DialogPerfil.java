    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nombre = jTextField1.getText().trim();
        int nivel = (int) jSpinner1.getValue();
        
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pon tu nombre", "ERROR", JOptionPane.ERROR_MESSAGE);
        } else if (nivel < 0) {
            JOptionPane.showMessageDialog(this, "Tiene que ser un número positivo", "ERROR", JOptionPane.ERROR_MESSAGE);
        } else {
            ventanaPadre.actualizarPerfil(nombre, nivel);
            this.dispose();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

