    private void jBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBorrarActionPerformed
        String texto = new String(jPasswordField1.getPassword());
        if (texto.length() > 0) {
            jPasswordField1.setText(texto.substring(0, texto.length() - 1));
        }
    }//GEN-LAST:event_jBorrarActionPerformed

    private void jOkActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jOkActionPerformed
        String pin = new String(jPasswordField1.getPassword());

        if (pin.length() < 4) {
            javax.swing.JOptionPane.showMessageDialog(this, "Introduce 4 dígitos");
            return;
        }

        if (pin.equals(PIN_CORRECTO)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Acceso concedido");
            this.dispose();
        } else {
            intentos++;
            jPasswordField1.setText("");
            if (intentos >= 3) {
                javax.swing.JOptionPane.showMessageDialog(this, "Tarjeta bloqueada", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                for (java.awt.Component c : jPanel1.getComponents()) {
                    c.setEnabled(false);
                }
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "PIN incorrecto. Intentos restantes: " + (3 - intentos));
            }
        }
    }//GEN-LAST:event_jOkActionPerformed

    private void jNum1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jNum1ActionPerformed
        javax.swing.JButton btn = (javax.swing.JButton) evt.getSource();
        String textoActual = new String(jPasswordField1.getPassword());

        if (textoActual.length() < 4) {
            jPasswordField1.setText(textoActual + btn.getText());
        }
    }//GEN-LAST:event_jNum1ActionPerformed

