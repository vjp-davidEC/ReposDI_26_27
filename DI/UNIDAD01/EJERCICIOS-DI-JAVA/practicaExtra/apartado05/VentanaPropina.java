    private double calcularPropina(double importe, int porcentaje) {
        return importe * (porcentaje / 100.0);
    }

    private void actualizarTotal() {
        try {
            double importe = Double.parseDouble(jTextField1.getText().trim());
            if (importe < 0) {
                throw new NumberFormatException();
            }

            int porcentaje = jSlider1.getValue();
            double propina = calcularPropina(importe, porcentaje);
            double total = importe + propina;

            if (jCheckBox2.isSelected()) {
                total = Math.ceil(total);
            }

            jLabel3.setText("Total: " + String.format("%.2f", total) + " €");
            jLabel3.setForeground(java.awt.Color.BLACK);
        } catch (NumberFormatException e) {
            jLabel3.setText("Importe no válido");
            jLabel3.setForeground(java.awt.Color.RED);
        }
    }

