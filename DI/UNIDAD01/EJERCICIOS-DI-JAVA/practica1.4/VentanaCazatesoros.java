    private void esconderTesoros() {
        Random rand = new Random();
        int tesorosEscondidos = 0;
        
        while (tesorosEscondidos < 5) {
            int posicionAleatoria = rand.nextInt(16);
            
            if (botones[posicionAleatoria].getName() == null) {
                botones[posicionAleatoria].setName("tesoro");
                tesorosEscondidos++;
            }
        }
    }
    
    private void actualizarMarcador() {
        jLabel2.setText("Puntos Usuario: " + puntosUsuario + " || Puntos CPU: " + puntosCPU);
    }
    
    private void jugarCPU() {
        Random rand = new Random();
        int pos = rand.nextInt(16);
        
        while (!botones[pos].isEnabled()) {
            pos = rand.nextInt(16);
        }
        
        JButton buttonCPU = botones[pos];
        
        if ("tesoro".equals(buttonCPU.getName())) {
            buttonCPU.setBackground(Color.YELLOW);
            puntosCPU++;
            tesorosRestantes--;
        } else {
            buttonCPU.setBackground(Color.DARK_GRAY);
        }
        
        buttonCPU.setEnabled(false);
        actualizarMarcador();
        
        turnoUsuario = true;
        
        if (tesorosRestantes == 0) {
            terminarJuego();
        }
    }
    
    private void terminarJuego() {
        String ganador;
        
        if (puntosUsuario > puntosCPU) {
            ganador = "--HAS GANADOO--";
        } else if (puntosCPU > puntosUsuario) {
            ganador = "--CPU HA GANADO--";
        } else {
            ganador = "--EMPATE--";
        }
        
        JOptionPane.showMessageDialog(this, "FIN DEL JUEGO\n" + ganador + "\nPuntos Usuario: " + puntosUsuario + " | Puntos CPU: " + puntosCPU);
        
        for (JButton button3 : botones) {
            button3.setEnabled(false);
        }
    }

