    private void botonPulsado(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonPulsado
        JButton button16 = (JButton) evt.getSource();
        
        if (!turnoUsuario || !button16.isEnabled()) {
            
        } else {
            if ("tesoro".equals(button16.getName())) {
                button16.setBackground(Color.ORANGE);
                puntosUsuario++;
                tesorosRestantes--;
            } else {
                button16.setBackground(Color.DARK_GRAY);
            }
            
            button16.setEnabled(false);
            actualizarMarcador();
            
            if (tesorosRestantes == 0) {
                terminarJuego();
            } else {
                turnoUsuario = false;
                jugarCPU();
            }
        }
    }//GEN-LAST:event_botonPulsado

