    private void jButtonAlert1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAlert1ActionPerformed
        if (aforoActual <= aforoMaximo) {
            aforoActual++;
            actualizarTexto();
        }
    }//GEN-LAST:event_jButtonAlert1ActionPerformed

    private void jButtonAlert2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAlert2ActionPerformed
        if (aforoActual > 0) {
            aforoActual--;
            actualizarTexto();
        } else {
            JOptionPane.showMessageDialog(this, "No hay aforo disponible", "AVISO", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButtonAlert2ActionPerformed

