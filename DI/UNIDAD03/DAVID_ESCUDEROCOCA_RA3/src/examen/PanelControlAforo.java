    private void actualizarTexto() {
        jLabel1.setText("Aforo actual: " + aforoActual);

        if (aforoActual >= aforoMaximo) {
            jButtonAlert1.setEnabled(false);
            calcularColor();
        } else {
            jButtonAlert1.setEnabled(true);
            calcularColor();
        }
    }
    
    public void calcularColor() {
        if (aforoActual * 0.08 > aforoMaximo) {
            jLabel1.setBackground(Color.RED);
        } else {
            jLabel1.setBackground(Color.BLACK);
        }
    }

