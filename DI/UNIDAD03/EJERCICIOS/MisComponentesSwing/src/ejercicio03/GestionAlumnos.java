    private void inicializarTabla() {
        modelo = new DefaultTableModel(new Object[][]{}, new String[]{"Nombre", "Curso"});
        jTable1.setModel(modelo);
    }

    private void inicializarEventos() {
        jButton1.addActionListener(new ActionListener() {
            @Override
            public void actionPerformed(java.awt.event.ActionEvent evt) {
                aniadirAlumno();
            }
        });

        jButton2.addActionListener(new ActionListener() {
            @Override
            public void actionPerformed(java.awt.event.ActionEvent evt) {
                borrarSeleccionado();
            }
        });
    }

    private void aniadirAlumno() {
        String nombre = jTextField1.getText().trim();
        String curso = jTextField2.getText().trim();

        if (nombre.isEmpty() || curso.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Rellena ambos campos", "Aviso", JOptionPane.WARNING_MESSAGE);
        } else {
            modelo.addRow(new Object[]{nombre, curso});

            jTextField1.setText("");
            jTextField2.setText("");
            jTextField1.requestFocus();
        }
    }

    private void borrarSeleccionado() {
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona una fila para borrar", "Aviso", JOptionPane.WARNING_MESSAGE);
        } else {
            modelo.removeRow(fila);
        }
    }

    public int getTotalAlumnos() {
        return modelo.getRowCount();
    }

    public void vaciarTabla() {
        modelo.setRowCount(0);
    }

