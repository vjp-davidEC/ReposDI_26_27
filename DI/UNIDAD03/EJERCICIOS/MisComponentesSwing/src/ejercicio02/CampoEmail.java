    private final Color COLOR_VALIDO = new Color(0, 153, 0);
    private final Color COLOR_INVALIDO = Color.RED;
    private final String REGEX_EMAIL = "^[\\w-\\.]+@([\\w-]+\\.)+[\\w-]{2,4}$";

