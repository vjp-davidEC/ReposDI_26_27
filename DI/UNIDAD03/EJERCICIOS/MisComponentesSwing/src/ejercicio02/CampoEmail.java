    private void inicializarEventos() {
        jTextField1.getDocument().addDocumentListener(new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) {
                validar();
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                validar();
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                validar();
            }
        });

        jButton1.addActionListener(new java.awt.event.ActionListener() {
            public void actionPerformed(java.awt.event.ActionEvent evt) {
                if (isEmailValido()) {
                    JOptionPane.showMessageDialog(null, "¡El correo electronico es valido!", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(null, "¡El correo electronico no es valido!", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        });
    }

    private void validar() {
        if (isEmailValido()) {
            jTextField1.setBorder(BorderFactory.createLineBorder(COLOR_VALIDO, 2));
        } else {
            jTextField1.setBorder(BorderFactory.createLineBorder(COLOR_INVALIDO, 2));
        }
    }

    public boolean isEmailValido() {
        String texto = jTextField1.getText().trim();
        return Pattern.matches(REGEX_EMAIL, texto);
    }

