    private void btnAnadirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAnadirActionPerformed
        
        String nombre = txtNombre.getText();
        String curso = txtCurso.getText();
        
        //Validación para no meter filas vacías y que curso es un número
        if (!nombre.isEmpty() && !curso.isEmpty() && curso.matches("\\d+")) {
            
            //Rescatamos el modelo de la tabla
            DefaultTableModel modelo = (DefaultTableModel) tablaAlumnos.getModel();

            //Añadimos la fila (no usamos ninguna clase)
            modelo.addRow(new Object[]{nombre, curso});

            //Limpiamos los campos de texto
            txtNombre.setText("");
            txtCurso.setText("");
            txtNombre.requestFocus(); //Devolvemos el cursor al primer campo
        }
        
    }//GEN-LAST:event_btnAnadirActionPerformed

    private void btnBorrarSeleccionadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarSeleccionadoActionPerformed
        
        int filaSeleccionada = tablaAlumnos.getSelectedRow();

        //getSelectedRow() devuelve -1 si no hay nada seleccionado
        if (filaSeleccionada != -1) {
            DefaultTableModel modelo = (DefaultTableModel) tablaAlumnos.getModel();
            modelo.removeRow(filaSeleccionada);
        }
        
    }//GEN-LAST:event_btnBorrarSeleccionadoActionPerformed


