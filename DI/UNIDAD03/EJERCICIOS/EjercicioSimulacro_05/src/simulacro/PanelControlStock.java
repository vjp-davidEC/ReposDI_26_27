    private void jButtonReponerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonReponerActionPerformed
        if (stockActual < stockMaximo) {
            stockActual++;
            actualizarTexto();
        }
    }//GEN-LAST:event_jButtonReponerActionPerformed

    private void jButtonVenderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonVenderActionPerformed
        if (stockActual > 0) {
            stockActual--;
            actualizarTexto();
        } else {
            JOptionPane.showMessageDialog(this, "No hay stock para vender", "AVISO", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButtonVenderActionPerformed

