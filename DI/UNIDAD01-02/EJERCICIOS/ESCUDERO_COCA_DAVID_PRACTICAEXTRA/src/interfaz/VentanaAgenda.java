    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nombre = jTextField1.getText().trim();
        String telefono = jTextField2.getText().trim();

        if (nombre.isEmpty() || !telefono.matches("\\d{9}")) {
            javax.swing.JOptionPane.showMessageDialog(this, "El nombre no puede estar vacío y el teléfono debe tener 9 dígitos", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
        } else {
            modelo.addRow(new Object[]{nombre, telefono});

            jLabel1.setText("Contador: " + modelo.getRowCount());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, selecciona una fila primero");
        } else {
            int confirmo = JOptionPane.showConfirmDialog(this, "¿Seguro que quieres eliminar este contacto?", "Confirmar", JOptionPane.YES_NO_OPTION);

            if (confirmo == JOptionPane.YES_OPTION) {
                modelo.removeRow(fila);
                jLabel1.setText("Contactos: " + modelo.getRowCount());
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

