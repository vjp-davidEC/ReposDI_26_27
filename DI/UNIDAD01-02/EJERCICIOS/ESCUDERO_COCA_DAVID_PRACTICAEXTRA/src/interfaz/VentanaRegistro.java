    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nombre = jTextField1.getText().trim();
        
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nombre de producto obligatorio", "Error", JOptionPane.ERROR_MESSAGE);
        } else {
            int cantidad = (int) jSpinner1.getValue();
            
            String categoria = "";
            
            if (jRadioButton1.isSelected()) {
                categoria = categoria + "Alimentación ";
            }
            if (jRadioButton2.isSelected()) {
                categoria = categoria + "Limpieza ";
            } 
            if (jRadioButton3.isSelected()) {
                categoria = categoria + "Electrónica ";
            }
            if (jRadioButton4.isSelected()) {
                categoria = categoria + "Sin categoría ";
            }
            
            Producto p = new Producto(nombre, cantidad, categoria);
            System.out.println("Producto guardado - Nombre: " + p.getNombre() + " | Cantidad: " + p.getCantidad() + " | Categoria: " + p.getCategoria());
            
            this.dispose();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

